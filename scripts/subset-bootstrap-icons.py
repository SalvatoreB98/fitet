#!/usr/bin/env python3
"""Generate a subset of the Bootstrap Icons font with only the icons used by the app.

Usage:
    python scripts/subset-bootstrap-icons.py

Outputs:
    public/fonts/bootstrap-icons-subset.woff2
    src/styles/bootstrap-icons-subset.css

The generated CSS replaces the full bootstrap-icons stylesheet imported in
src/main.tsx. Re-run this script whenever you add or remove a `bi-*` icon.
"""

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
BOOTSTRAP_ICONS = ROOT / "node_modules" / "bootstrap-icons"
ICONS_CSS = BOOTSTRAP_ICONS / "font" / "bootstrap-icons.css"
ICONS_WOFF2 = BOOTSTRAP_ICONS / "font" / "fonts" / "bootstrap-icons.woff2"
OUT_FONT = ROOT / "public" / "fonts" / "bootstrap-icons-subset.woff2"
OUT_CSS = SRC / "styles" / "bootstrap-icons-subset.css"

# Icons chosen at runtime through template literals, so they are not detected
# as literal `bi-*` tokens by the source scan.
DYNAMIC_ICONS = {
    "bi-arrows-collapse",
    "bi-arrows-expand",
}

BASE_RULES = """/* Auto-generated by scripts/subset-bootstrap-icons.py. Do not edit manually. */
@font-face {
  font-family: "bootstrap-icons";
  font-display: block;
  font-style: normal;
  font-weight: normal;
  src: url("/fonts/bootstrap-icons-subset.woff2?v={version}") format("woff2");
}

.bi::before,
[class^="bi-"]::before,
[class*=" bi-"]::before {
  display: inline-block;
  font-family: bootstrap-icons !important;
  font-style: normal;
  font-weight: normal !important;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  vertical-align: -.125em;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}
"""


def collect_icon_names() -> set[str]:
    names: set[str] = set(DYNAMIC_ICONS)
    for path in SRC.rglob("*"):
        if path.suffix not in {".ts", ".tsx", ".js", ".jsx", ".html", ".css"}:
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        names.update(re.findall(r"bi-[a-z0-9-]+", text))
    # Drop partial tokens such as `bi-chevron-` produced by template literals.
    return {name for name in names if not name.endswith("-")}


def load_glyph_map() -> dict[str, str]:
    css = ICONS_CSS.read_text(encoding="utf-8")
    pairs = re.findall(
        r"\.(bi-[a-z0-9-]+)::before\s*\{\s*content:\s*\"\\([0-9a-fA-F]+)\";\s*\}",
        css,
    )
    return {name: code.lower() for name, code in pairs}


def main() -> int:
    if not ICONS_CSS.exists() or not ICONS_WOFF2.exists():
        print("Bootstrap Icons non installato: esegui prima `npm install`.", file=sys.stderr)
        return 1

    names = collect_icon_names()
    glyphs = load_glyph_map()

    missing = sorted(name for name in names if name not in glyphs)
    if missing:
        print("Icone non trovate nel font Bootstrap Icons:", ", ".join(missing), file=sys.stderr)
        return 1

    codepoints = [glyphs[name] for name in sorted(names)]
    OUT_FONT.parent.mkdir(parents=True, exist_ok=True)
    OUT_CSS.parent.mkdir(parents=True, exist_ok=True)

    command = [
        sys.executable,
        "-m",
        "fontTools.subset",
        str(ICONS_WOFF2),
        f"--output-file={OUT_FONT}",
        "--flavor=woff2",
        "--unicodes=" + ",".join(f"U+{code}" for code in codepoints),
        "--no-hinting",
        "--desubroutinize",
    ]
    import subprocess

    subprocess.run(command, check=True)

    version = hashlib.sha256(OUT_FONT.read_bytes()).hexdigest()[:10]
    rules = [BASE_RULES.replace("{version}", version)]
    for name in sorted(names):
        rules.append(f'.{name}::before {{ content: "\\{glyphs[name]}"; }}\n')

    OUT_CSS.write_text("".join(rules), encoding="utf-8")

    size_kb = OUT_FONT.stat().st_size / 1024
    print(
        f"Generati {len(names)} glifi in {OUT_FONT.relative_to(ROOT)} "
        f"({size_kb:.1f} KiB) e {OUT_CSS.relative_to(ROOT)}."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
